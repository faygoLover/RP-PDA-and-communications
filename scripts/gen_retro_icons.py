ORDER = ["CHATS", "CONTACTS", "PROFILE", "LOCK", "UNLOCK", "CLOSE", "BACK", "SEND",
         "PLUS", "GROUP", "CHANNEL", "BELL", "PDA_ONLY", "MUTE", "MEMBERS", "LEAVE",
         "KICK", "CROWN", "REPLY", "TRASH", "COPY", "KEY", "SILENT", "SOUND",
         "ACCOUNTS", "LOG", "SWITCH", "GIVE", "TELEPORT", "EDIT", "BLOCK", "CHECK",
         "SEARCH", "MESSAGE", "PDA", "REFRESH", "PERSON_ADD", "SYSTEM", "GLOBE", "EYE"]


def build():
    out = Image.new("RGBA", (128, 80), (0, 0, 0, 0))
    for n, name in enumerate(ORDER):
        rows = ICONS[name]
        assert len(rows) == 12 and all(len(r) == 12 for r in rows), name
        ox, oy = (n % 8) * 16 + 2, (n // 8) * 16 + 2
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == "#":
                    out.putpixel((ox + x, oy + y), (255, 255, 255, 255))
    return out


if __name__ == "__main__":
    atlas = build()
    path = os.path.join(ROOT, "icons_retro.png")
    atlas.save(path)
    print("retro icons:", len(ORDER), "->", path)
    if len(sys.argv) > 2 and sys.argv[1] == "--preview":
        bg = Image.new("RGBA", atlas.size, (6, 20, 8, 255))
        tint = Image.new("RGBA", atlas.size, (120, 255, 140, 255))
        bg.paste(tint, (0, 0), atlas)
        bg.resize((atlas.width * 6, atlas.height * 6), Image.NEAREST).save(sys.argv[2])
